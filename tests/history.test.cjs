const assert=require('node:assert/strict');
const Engine=require('../engine.js');
const {world}=require('./fixtures.cjs');
const game=new Engine(world);
assert.equal(game.state.conversations.length,1);
assert.equal(game.conversation.entries.length,1);
assert.equal(game.state.history[0].label,'Voyage begun');
assert.equal(game.state.history[0].date,'1453-05-01T00:00:00.000Z');
const initial=game.conversation;
game.cast('scroll_en');
assert.ok(initial.entries[0].notes.some(note=>note.via==='Translation scroll'));
const choice=game.visibleChoices().find(({choice})=>choice.phrase&&game.available(choice));
const replyNotes=game.notes(choice.choice.phrase,choice.choice.language||game.language);
game.choose(choice.index);
assert.equal(initial.entries[1].speaker,'player');
assert.deepEqual(initial.entries[1].notes,replyNotes);
assert.equal(initial.entries.length,choice.choice.next?3:2);
const snapshot=JSON.stringify(initial);
game.open('ada');
assert.equal(game.state.conversations.length,2);
assert.equal(JSON.stringify(initial),snapshot);
assert.equal(game.conversation.entries[0].notes.length,0);
const before=game.state.history.length;
assert.throws(()=>game.travel('krakow'));
assert.equal(game.state.history.length,before);
game.state.milestones.push(...world.locations.flatMap(location=>[location.id,location.milestone].filter(Boolean)));
game.state.inventory.map=1;
const destination=world.locations.find(location=>location.id!==game.state.location&&game.canTravel(location.id));
assert.ok(destination);
game.travel(destination.id);
const travel=game.state.history.find(event=>event.label==='Travelled');
assert.equal(travel.from,'prague');
assert.ok(travel.days>1);
assert.equal(travel.date,new Date(Date.UTC(1453,4,1+travel.days)).toISOString());
assert.equal(game.currentDate,travel.date);
assert.ok(game.travelDays('london','prague')>game.travelDays('bratislava','prague'));
assert.equal(game.travelDays('prague','prague'),0);
const day=game.state.voyageDay;game.travel(destination.id);assert.equal(game.state.voyageDay,day);
assert.equal(travel.location,destination.id);
assert.equal(game.conversation.location,destination.id);
game.reset();
assert.equal(game.state.conversations.length,1);
assert.equal(game.state.history.length,1);
assert.equal(game.state.voyageDay,0);
console.log('Passed: transcripts, translation snapshots, replay separation, failed travel, travel history, and reset.');

